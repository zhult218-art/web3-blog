/**
 * 获取经典图书列表（元数据）
 * @returns {Promise<Array<{id,title,author,era,category,summary,cover}>>}
 */
export async function getClassicBookList() {
  // 本地数据，模拟异步返回
  return BOOKS.map(b => ({
    id: b.id,
    title: b.title,
    author: b.author,
    era: b.era,
    category: b.category,
    summary: b.summary,
    cover: b.cover,
  }))
}

/**
 * 获取单本图书详情（含 Markdown 全文）
 * @param {string} id 书籍 id
 * @returns {Promise<{id,title,author,era,summary,content}>}
 */
export async function getClassicBookDetail(id) {
  const b = BOOKS.find(x => x.id === id)
  if (!b) throw new Error('未找到此书')
  return {
    id: b.id,
    title: b.title,
    author: b.author,
    era: b.era,
    summary: b.summary,
    content: b.content,
  }
}

export default { getClassicBookList, getClassicBookDetail }
