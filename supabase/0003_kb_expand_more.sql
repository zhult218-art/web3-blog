## 七、选型原则与排错清单

**选型**：
- 板内高速外设（Flash/屏）→ SPI。
- 板内多个低速传感器 → I2C。
- 调试/模块 AT 口 → UART。
- 车规/工控/抗干扰长距离 → CAN 或 RS-485。
- 板间 MCU 通讯，距离中、引脚够 → UART；引脚紧 → I2C。

**通用排错清单**：
1. 先共地：90% 的"通讯不通"是地线没接。
2. 波特率/速率一致。
3. 用逻辑分析仪或示波器看实际波形，别只盯软件。
4. TX/RX、SCL/SDA、MOSI/MISO 接线方向。
5. 上拉电阻别省（I2C/1-Wire/CS 之类开漏/开集输出必上拉）。
6. 电平匹配：3.3V vs 5V 用电平转换或选 5V 容忍 IO。
