## 九、给开发者的选型与排错

1. 高吞吐外设选 PCIe，热插拔选 USB，存储首选 NVMe。
2. 带宽先看 GB/s 再看 lane 数和版本，别被 GT/s 唬住。
3. NVMe SSD 慢先查：PCIe 通道数、主板 bifurcation、是否跑在 SATA M.2 口上。
4. USB 速度不达标？换线（Type-C 线分 USB2-only 和全功能）、换口（确认是 SS 口）。
5. 内存带宽吃满？开双通道、用满 DDR 频率、确认内存条插对插槽。

