## 一、Tailscale 是什么，解决了什么

你有一台家里的 NAS、一台公司电脑、一台云服务器、一部手机，彼此分散在不同网络（NAT 后、办公室、机房）。想让手机访问家里 NAS 的 SMB、让笔记本连云服务器的内网端口，传统做法是搭 VPN（OpenVPN/WireGuard）+ 公网中转 + 证书管理——一整套基础设施，运维成本不低。

**Tailscale** 基于 WireGuard，把这些全打包成一个"零配置 mesh"：
- 装客户端、登录账号，设备自动加入一个 tailnet（你的私有虚拟网络）。
- 每台设备拿到一个稳定的 `100.x.x.x` 私网 IP（CGNAT 段）。
- 设备两两直连（P2P 打洞），打不通时走它的中继 DERP。
- 端到端加密（WireGuard），密钥自动轮转。

对开发者等于"一键把所有设备拉进同一个局域网"，写代码时用 100.x IP 访问任意设备。

## 二、核心概念

- **Tailnet**：你的私有虚拟网络。个人版一个 tailnet 最多 100 设备，足够个人/小团队用。
- **Node**：tailnet 里的一台设备，有稳定的 tailnet IP 和 MagicDNS 名字（如 `nas.tail-xxx.ts.net` 或自定义名 `nas`）。
- **MagicDNS**：tailnet 内置 DNS，用设备名直连（`ssh user@nas`），不用记 IP。
- **ACL**：访问控制列表，声明谁能访问谁的什么端口（"手机只能访问 NAS 的 22 和 445"）。默认全开，生产建议收紧。
- **Exit Node**：出口节点，把所有流量（包括上公网）从一个节点出去，类似 VPN 翻墙。
- **Subnet Router**：子网路由器，把整个内网网段暴露给 tailnet，不必每台设备装客户端。
- **DERP**：Tailscale 的中继服务器，P2P 打洞失败时兜底转发。自建 DERP 可降延迟、隐私更可控。

## 三、安装与基础用法

各平台都有客户端：Windows/macOS 装官方 GUI；Linux 一行脚本：

```bash
curl -fsSL https://tailscale.com/install.sh | sh
sudo tailscale up
```

`tailscale up` 后浏览器跳转登录页，授权设备入网。成功后：

```bash
tailscale status        # 看所有节点状态、直连/中继
tailscale ip            # 本机 tailnet IP
ssh user@nas            # MagicDNS 直连另一台
```

退出/关机不影响其他设备，P2P 自动重建。

## 四、子网路由器（Subnet Router）：让没装客户端的内网设备也能访问

家里有一台路由器、几台 IoT 设备、一台打印机，不可能都装 Tailscale。让一台常开的 Linux（树莓派/NAS/小主机）做子网路由器，把整个 `192.168.1.0/24` 暴露给 tailnet：

```bash
# 在子网路由器节点上
sudo tailscale up --advertise-routes=192.168.1.0/24
```

然后在管理后台（或命令行）批准这条路由：

```bash
# 在批准端的节点（同一 tailnet 的另一台机器）
sudo tailscale up --accept-routes
```

批准后，tailnet 里任何机器都能直接访问 `192.168.1.x`，像在同一个 LAN。子网路由器本身要打开 IP 转发：

```bash
echo 'net.ipv4.ip_forward = 1' | sudo tee -a /etc/sysctl.d/99-tailscale.conf
sudo sysctl -p /etc/sysctl.d/99-tailscale.conf
```

注意：子网路由器暴露的是**它所在 LAN 的网段**，跨 NAT 时路由器要做相应 NAT 配置（家用一般有 NAT 网关，子网路由器出口自动 SNAT）。

## 五、Exit Node：把出口流量走某一节点

出差/咖啡店 WiFi 不安全，想所有流量都从家里的节点出去：

家里那台 Linux 节点声明自己愿意做出口：

```bash
sudo tailscale up --advertise-exit-node
```

笔记本端选这台为 exit node：

```bash
sudo tailscale up --exit-node=<家里节点IP或名字>
```

之后所有公网流量从家里节点出去，家里宽带当出口。配合家里有干净 IP/翻墙链路时很方便。

## 六、ACL：收紧访问权限

默认 tailnet 全互通，团队/生产建议收紧。管理后台 ACL 编辑 YAML/JSON 矩阵：

```jsonc
{
  "acls": [
    // 个人设备间全互通
    { "action": "accept", "src": ["my-devices"], "dst": ["*:*"] },
    // 同事只能访问云服务器的 22/443
    { "action": "accept", "src": ["coworkers"], "dst": ["cloud-server:22,443"] }
  ]
}
```

`src`/`dst` 都可以用 tag、用户、设备组。生产环境给服务器打 `tag=server`，按 tag 授权。

## 七、MagicDNS 与 HTTPS

MagicDNS 默认开，设备名直接解析。进阶：

- 自定义域名：付费版可绑 `*.yourdomain.com`，让 `nas.yourdomain.com` 走 tailnet。
- Tailscale Serve：把本机某端口通过 tailnet 暴露成 HTTPS（自动证书），如 `tailscale serve --bg --https 443 localhost:8080` → `https://nas.<tailnet>.ts.net` 公网可达但走 tailnet。
- Tailscale Funnel：把内网服务公开到公网（带 HTTPS），不用反向代理+证书，适合临时分享。

## 八、DERP 自建：中继可控

P2P 打洞失败时（对称 NAT、防火墙严），Tailscale 走官方 DERP 中继。官方 DERP 在境外，国内延迟高、偶尔不稳。自建 DERP：

1. 一台公网 VPS，开放 443/TCP、3478/UDP。
2. 用官方 docker 镜像 `ghcr.io/fredliang44/derper` 或 `fredliang44/derper`。
3. 在管理后台 ACL 加 DERP map，指向自建域名。

国内自建 DERP 后，无法直连的设备间走自建中继，延迟大幅下降，隐私也更好。

## 九、实战场景

- **家里 NAS + 公司电脑**：家里 NAS 装 Tailscale 做子网路由器，公司电脑直连 `smb://192.168.1.10`，文件同步像在 LAN。
- **云服务器内网互通**：多台云机都装 Tailscale，用 100.x IP 互访，不必开公网端口，安全面大幅收窄。
- **手机连家里 Docker**：手机连 tailnet，直接 `http://nas:8123` 访问 Home Assistant。
- **iOS/Android 抓包本地服务**：手机走出口节点 = 家里节点，浏览器调试家里服务。
- **临时分享给外人**：用 Tailscale Funnel 给某个本地端口一个公网 HTTPS 链接，阅后即焚。

## 十、常见坑与排错

1. **打不通走 DERP 慢**：`tailscale status` 看 `direct` 还是 `relay`。relay 慢正常。检查 NAT 类型、UDP 是否被防火墙挡（对称 NAT 多半要走 DERP）。
2. **子网路由不通**：先在子网路由器本机 ping 目标，确认网内可达；再确认 `--accept-routes` 在访问端开了；最后看 ACL 是否放行。
3. **MagicDNS 解析失败**：用 IP 直连先验证；DNS 被 systemd-resolved/路由器劫持时常见，检查 `/etc/resolv.conf`。
4. **Exit node 不生效**：确认 `--accept-dns` 开了、出口节点本机能上公网、内核转发开了。
5. **Linux 客户端登录态丢失**：`tailscale up` 而非 `tailscale up --authkey=xxx` 用于无人值守，authkey 在管理后台生成。

## 十一、安全模型

- WireGuard 端到端加密，Tailscale 服务端看不到内容（DERP 中继时也只是转发密文）。
- 节点身份绑定到你的账号（OAuth/SSO），节点 key 自动轮转。
- ACL + tag 做最小权限。
- 与传统 VPN 比，没有了"中心 VPN 服务器单点"，mesh 直连减少攻击面。

