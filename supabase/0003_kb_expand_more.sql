|---|---|---|---|---|
| PCIe 4.0 ×16 | 点对点 | 64 GB/s 双向 | μs | GPU、NVMe |
| USB 3.2 Gen2 | 主从 | 1.2 GB/s | 数十μs | 外设、移动盘 |
