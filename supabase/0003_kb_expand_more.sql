## 一、核心矛盾：CPU 比 内存 快 100 倍

现代 CPU 主频几个 GHz，一拍执行多条指令；而 DRAM 访问延迟约 80–120ns，相当于 CPU 白等上百拍。如果每条 `load` 都直接打 DRAM，CPU 利用率会低到 1%。

**存储层级（Memory Hierarchy）** 就是为填这个鸿沟而生的：用越快越小的介质做缓存，越慢越大的介质做后盾，靠"局部性"把命中率顶上去。

```
寄存器  ←  L1  ←  L2  ←  L3  ←  主存 DRAM  ←  SSD  ←  HDD/网盘
 0周期   ~1ns   ~4ns   ~12ns   ~80-120ns   ~50-150μs  ~10ms
 速度递减、容量递增、每位成本递减
```

每一层都是下一层的"缓存"。命中就在上一层解决，未命中就下沉。这个层层兜底的结构，是"程序跑得快"的全部秘密。

## 二、局部性原理：缓存能生效的根本前提

缓存之所以有效，是因为程序天然有局部性：

- **时间局部性**：刚访问过的数据很快会再被访问。循环里的计数变量、热点函数的栈帧。
- **空间局部性**：访问了一个地址，附近地址大概率也会被访问。数组遍历、指令顺序取。

CPU 缓存按 **缓存行（cache line，通常 64B）** 为单位加载，一次拉一整行，正好吃下空间局部性。所以遍历数组按行快、按列慢；遍历链表慢（节点散布在堆各处）。

## 三、缓存行与映射方式

缓存不是按字节存的，而是按行存。每行 64 字节（主流 x86/ARM）。一个 `int` 只占 4 字节，但只要访问其中一个，整行 64B 都会被加载进缓存。

**映射方式**：缓存行怎么对应内存地址？

- **直接映射**：每个内存块只能放进缓存的固定一格。硬件简单，但冲突多——两个热点变量映射到同一行会互相把对方挤出去（conflict miss）。
- **组相联**：每个内存块可放进 N 个候选行之一（N 路）。N 越大冲突越少，但查找电路越复杂。主流 L1 是 8 路或更小，L2/L3 常常十几到几十路。
- **全相联**：任意内存块可放任意行。灵活但硬件开销大，只用于 TLB 这类小结构。

地址结构：`tag | set index | block offset`。`set index` 决定落在哪一组，`tag` 在组内多路比较，`offset` 定位行内字节。

## 四、写策略：写命中之后怎么办

- **写直达（Write-Through）**：写命中后同时更新缓存和下一层。简单、一致性好，但写操作慢（每次都下沉）。
- **写回（Write-Back）**：只更新缓存，标记该行为脏（dirty），被替换时才写回下一层。快，但复杂，需要脏位。现代多级缓存普遍用写回。

**写未命中**：
- **写分配（Write-Allocate）**：先把数据所在行加载进缓存，再写。配合写回。
- **非写分配（No-Write-Allocate）**：直接写下一层，不进缓存。常配合写直达。

经验法则：**读未命中用写分配（拉进来利用局部性），写未命中可考虑绕过缓存**。但具体策略 CPU 已固化，程序员能调的是数据布局。

## 五、替换策略：缓存满了踢谁

- **LRU**：扔最久没用的。最常被模拟和讨论，但真实 CPU 因成本高，多用 **伪 LRU（PLRU）**。
- **随机替换**：硬件实现便宜，实际表现意外地不差，冲突更平滑。
- **FIFO**：先进先出，最简单，但效果差（刚进来的可能正是马上要用的）。

替换策略对程序员是黑盒，但理解它有助于预测性能。

## 六、缓存一致性：多核不能各写各的

多核各自有 L1/L2，共享 L3。如果核 A 把 `x` 改在自己 L1 里（写回，未同步），核 B 读 `x` 会拿到旧值——数据不一致。

主流协议 **MESI**：每行有四种状态

- **M（Modified）**：本核独占且已改，主存是旧值。
- **E（Exclusive）**：本核独占未改，与主存一致。
- **S（Shared）**：多核共享，都未改，与主存一致。
- **I（Invalid）**：本核这份已失效。

当核 A 写一个 S 状态的行，要先发 **无效化信号** 让其他核把该行置 I，A 才升为 M。核 B 再读就得从 A 拉最新值（通过 **MOESI** 的 Owned 或直接转发）。

**伪共享（False Sharing）**：两个无关变量恰好落在同一个 64B 缓存行里。核 A 改变量 a，会把核 B 缓存里同行的变量 b 也置 I，B 读 b 就要跨核同步——并发性能崩塌。**对策**：对高频并发写的变量做缓存行对齐填充（`alignas(64)` / `__attribute__((aligned(64)))`），或用 `thread_local`。

## 七、TLB 与虚拟内存：地址翻译也要缓存

程序用虚拟地址，访问前要翻译成物理地址（页表）。一次访存如果走完整页表查询（多级页表）要 4–5 次内存访问，不可接受。

**TLB（Translation Lookaside Buffer）** 是页表项的缓存，命中率极高（>99%）。TLB 未命中叫 page walk，要走硬件页表遍历，慢。

大页（HugePages，2MB/1GB）能让一条 TLB 项覆盖更多内存，减少 TLB 压力。数据库、大数组场景开大页有可见收益。

## 八、为什么顺序读比随机读快这么多

- 顺序读命中预取器（prefetcher）：硬件检测到地址线性递增，提前把下一行拉进缓存，命中率高到飞起。
- 随机读预取失效，每次都吃 DRAM 延迟。
- DRAM 本身也喜欢行激活（row activate）后顺序读，随机访问每拍要重新激活行，慢一个量级。

这就是为什么数据库索引扫、归并排序、矩阵按行遍历快，而哈希探测、链表跳转慢。

## 九、实战：缓存对程序性能的真实影响

**矩阵乘法按 ijk 还是 ikj？** 看似等价，实则相差数倍。

```c
// 按行遍历结果矩阵，命中缓存
for (i) for (j) for (k)
    c[i][j] += a[i][k] * b[k][j];
```

`b[k][j]` 的 j 在最内层，是按列遍历 b，跨缓存行跳跃，命中率低。改成 `ikj` 顺序：

```c
for (i) for (k) for (j)
    c[i][j] += a[i][k] * b[k][j];
```

`c[i][j]` 和 `b[k][j]` 都按行遍历，命中预取，性能往往提升 2–3 倍。这就是**循环重排**优化，纯算法没变，只换了访问顺序。

**数据布局**：AoS（Array of Structures）vs SoA（Structure of Arrays）。游戏引擎从 AoS 改 SoA，因为只关心 position 时不必把 color 一起加载进缓存行，减少浪费。SIMD 友好、缓存友好。

**链表 vs 数组**：链表节点散在堆上，遍历每跳一次都吃 cache miss；数组连续，预取器吃到饱。所以"动态数组 + 倍增扩容"通常比链表快。

## 十、性能分析三板斧

- **命中率**：`L1 miss rate`、`LLC miss rate`。LLC（末级缓存）命中率是程序"够不够快"的关键指标。
- **CPI（Cycles Per Instruction）**：理想 < 1（超标量），cache miss 抖到几甚至几十。
- **roofline 模型**：横轴运算强度（FLOP/Byte），纵轴性能上限，判断程序是 compute-bound 还是 memory-bound。

工具：`perf stat` 看 cache-misses、`perf c2c` 看伪共享、Intel VTune、`valgrind --tool=cachegrind`。Linux `cachestat`、`bpftrace` 也能盯。

## 十一、给应用开发者的清单

1. 热点数据紧凑排布，让一次缓存行加载吃下更多有用数据。
2. 顺序访问优先于随机访问。
3. 多线程高频写的共享变量做缓存行对齐，避免伪共享。
4. 大数据集考虑分块（blocking/tiling），让工作集塞进 L1/L2。
5. 链表谨慎用，能用数组用数组。
6. 跨平台 SIMD（如 highway、sleef）通常也按 SoA 组织数据。

