## 一、为什么要有总线

CPU 自己只会算，数据从哪来、算完往哪送？靠总线（bus）——一组标准化的物理通道和协议，把 CPU、内存、外设连起来。不同的设备带宽、延迟、拓扑要求天差地别，所以演化出一堆并行/串行、点对点/共享的总线标准。

这篇文章把桌面/服务器/嵌入式里最常见的几类总线一次过完，附带宽对照表和选型要点。

## 二、总线带宽的单位：别被数字绕晕

- **GT/s（GigaTransfers per second）**：每秒多少次传输，是"线上的信号事件"频率，不等于数据带宽。
- **GB/s（GigaBytes per second）**：每秒多少字节，才是真带宽。
- **编码开销**：PCIe 2.0 用 8b/10b 编码，10 bit 里 2 bit 是开销，所以 5 GT/s × 1B/transfer × 80% ≈ 4 Gb/s = 0.5 GB/s per lane per direction。PCIe 3.0 起 128b/130b，开销降到 1.5%。
- **方向**： PCIe 是双工，单 lane 双向各算。

记住：**厂商爱标 GT/s 吸引眼球，工程师要看 GB/s 才落地**。

## 三、PCIe：点对点高速串行

PCIe（PCI Express）是当代外设互联的绝对主力，从显卡、NVMe SSD 到网卡加速卡全走它。

**拓扑**：点对点（不是共享总线），每条 lane 是一对差分发送 + 一对差分接收。多 lane 并行（×1、×4、×8、×16）翻倍带宽，设备协商用最少 lane 数。

**版本对照（单 lane 单向带宽）**：

| 版本 | 信号率 | 单向带宽/lan | 典型用途 |
|---|---|---|---|
| PCIe 3.0 | 8 GT/s | ~1 GB/s | 主流存量 |
| PCIe 4.0 | 16 GT/s | ~2 GB/s | NVMe Gen4、新显卡 |
| PCIe 5.0 | 32 GT/s | ~4 GB/s | 服务器 NVMe、AI 卡 |
| PCIe 6.0 | 64 GT/s | ~8 GB/s | 2024 起 HPC/网络 |

一个 ×16 插槽在 PCIe 4.0 上双向 ≈ 64 GB/s，足够喂饱高端 GPU。

**协议层**：事务层（TLP）/数据链路层/物理层。设备有 BAR（Base Address Register）声明自己需要多大地址空间，CPU 通过 MMIO 读写设备寄存器。配置空间由 PCIe 枚举扫描时分配。

**枚举与中断**：开机 BIOS/UEFI 扫总线、分配 BAR、设置中断（MSI/MSI-X 用消息中断而非引脚中断，延迟低、可多向量，现代设备首选）。

**实战要点**：
- 显卡要 ×16 满血，插 ×8 会减半。
- NVMe Gen4 SSD 接 PCIe 3.0 主板会降速到 Gen3 顶。
- 服务器 bifurcation：把一个 ×16 拆成 ×4×4 接多块 NVMe，要主板和 CPU 支持。

## 四、USB：通用即插即用

USB 把"难插"的串口/并口干掉了，统一成一种口。但口型（Type-A/B/C）、协议（2.0/3.x/4）、供电（PD）三件事要分开看。

**协议版本**：

| 版本 | 俗称 | 带宽 | 备注 |
|---|---|---|---|
| USB 1.1 | Full Speed | 12 Mb/s | 已淘汰 |
| USB 2.0 | Hi-Speed | 480 Mb/s | 仍用于键鼠/低速 |
| USB 3.0/3.1 Gen1/USB 3.2 Gen1 | SS | 5 Gb/s | ~0.5 GB/s |
| USB 3.1 Gen2 / USB 3.2 Gen2 | SS 10 | 10 Gb/s | ~1.2 GB/s |
| USB 3.2 Gen2x2 | SS 20 | 20 Gb/s | 需 Type-C 双通道 |
| USB4 | — | 40 Gb/s | 基于 Thunderbolt 3 协议 |
| USB4 v2 | — | 80 Gb/s | 2024 新品 |

**Type-C 不是协议**，它是一种接口形状，能跑 USB 2.0 到 USB4 任一协议，还能叠加 DP Alt Mode、PD 供电。一根线到底跑多少，要看里面接了什么 controller。

**供电（PD）**：USB PD 3.1 最高 240W（48V/5A），笔记本、显示器都能一根线供电+传数据。

**协议栈**：USB 是主从结构，Host 轮询设备（不是中断驱动），所以延迟比 PCIe 高、CPU 占用也高。USB 3.x 引入双总线（SS 单独差分对），与 2.0 并存于同一根线。

**嵌入式端**：STM32/ESP32 的 USB 多为 Device 模式（外设身份），少数有 OTG 能当 Host。

## 五、SATA 与 NVMe：存储接口的两代

**SATA**：串行 ATA，最高 6 Gb/s（~600 MB/s 实际）。机械盘时代标准，SSD 时代瓶颈——SATA SSD 永远跑不到 1 GB/s。

**SAS**：服务器版 SATA，全双工、可挂更多盘、可靠性高，转速 10K/15K。

**NVMe**：不是"另一种 SATA"，而是**直接走 PCIe 的存储协议**。它绕开 AHCI（给机械盘设计的命令队列深度只有 1 的老协议），用多队列（每核一个队列、深度可达 64K）直连 PCIe，延迟从 AHCI 的毫秒级降到几十微秒。

| 接口 | 协议 | 典型带宽 | 队列深度 | 延迟 |
|---|---|---|---|---|
| SATA SSD | AHCI | ~550 MB/s | 1（NCQ 32） | ~100μs |
| NVMe Gen3 x4 | NVMe | ~3.5 GB/s | 64K×多队列 | ~20-50μs |
| NVMe Gen4 x4 | NVMe | ~7 GB/s | 同上 | ~10-30μs |
| NVMe Gen5 x4 | NVMe | ~14 GB/s | 同上 | ~10μs |

**形态**：M.2（小条）、U.2（服务器盘）、AIC（插卡）、EDSFF（服务器新标准）。M.2 也有走 SATA 的（key B+M），别和 NVMe M key 混。

## 六、DDR：主存总线

DDR（Double Data Rate）SDRAM 是主存，CPU 与内存之间的总线。DDR 在时钟上下沿都传数据，所以"等效速率"是时钟的 2 倍。

| 代际 | 标称 | 数据率 | 单通道带宽 | 量产年份 |
|---|---|---|---|---|
| DDR3 | 1600 | 1600 MT/s | ~12.8 GB/s | 2007 |
| DDR4 | 3200 | 3200 MT/s | ~25.6 GB/s | 2014 |
| DDR5 | 6400 | 6400 MT/s | ~51.2 GB/s | 2020 |
| LPDDR5X | 8533 | 8533 MT/s | 移动端 | 2022 |

**双通道**：把两条 64-bit 内存并联成 128-bit，带宽翻倍。游戏本/工作站要插两条同规格内存才能开双通道。

**DIMM/rank/bank/channel**：channel 是 CPU 到内存的独立总线（每通道 64/72 bit），rank 是一组并行响应的芯片（双 rank 比 单 rank 略快但更贵），bank 是 rank 内部可独立激活的子阵列。

**DDR5 的变化**：片上 ECC、双 32-bit 子通道（单条即可双通道、减少冲突）、PMIC 上模组（电源管理上移）、更高频率。服务器还有 RDIMM/LRDIMM（带缓冲，容量大、频率略降）。

## 七、嵌入式常用：I2C / SPI / UART / CAN

这块在另一篇里详述，这里只点总线定位：

- **I2C**：两线（SCL/SDA）、多主、地址寻址、慢（100k–1M/3.4M）。配传感器、EEPROM。
- **SPI**：四线、主从、片选寻址、快（几十 Mbps）。配 Flash、屏、ADC。
- **UART**：点对点异步、调试串口标配。
- **CAN**：差分总线、汽车/工控、可靠仲裁。

