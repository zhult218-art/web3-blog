## 一、为什么嵌入式有这么多"串口"

MCU 引脚少、要连的外设多：传感器、EEPROM、Flash、屏、调试口、另一个 MCU、电机驱动……如果每种外设都拉一组专属并行总线，引脚立刻爆。所以嵌入式世界演化出几条"用极少的线、按协议分时复用"的串行总线，各有定位：

- **UART**：点对点、异步、调试与模块间通讯。
- **I2C**：两线、多主多从、地址寻址、慢速传感器总线。
- **SPI**：四线、主从、片选、高速 Flash/屏。
- **CAN**：差分、总线拓扑、可靠仲裁、汽车工控。

下文逐个拆接线、时序、优劣与典型坑。

## 二、UART：最朴素的异步串口

**接线**：TX、RX、GND，三根线即可点对点通信（双方 TX/RX 交叉对接）。无时钟线，靠双方约定波特率对齐。

**帧格式**：1 个起始位（拉低）+ 5–9 数据位 + 1 校验位（可选）+ 1/1.5/2 停止位。空闲时线为高。

**波特率**：双方必须一致，常用 9600/115200/921600。波特率误差 > 2–3% 会错位。115200 在 3.3V MCU 间稳定，过高（如 3M+）要算引脚电容和线长。

**异步的代价**：无时钟线，靠双方各自时钟对齐。所以波特率不能太高、距离不能太长（一般 < 1m，长距离加 RS-232/RS-485 电平转换）。

**典型用途**：
- 调试 printf 日志（最常见）。
- GPS 模块、蓝牙模组、LoRa 模组的 AT 命令口。
- 两个 MCU 间点对点通讯。

**常见坑**：
1. TX/RX 接反 → 什么也收不到。先互换试试。
2. 波特率不匹配 → 收到乱码。用逻辑分析仪或示波器量一个已知字节（如 0x55）反推波特率。
3. 电平不匹配：3.3V MCU 直连 5V 设备可能烧 IO，加电平转换或限流。
4. 空闲总线电平必须为高，上拉电阻别省。
5. 乱码首先怀疑波特率，其次是地线未共地。

## 三、I2C：两线多主多从总线

**接线**：SCL（时钟）、SDA（数据）、GND，两根线挂多个设备，每个设备有 7 位（或 10 位）硬件地址。两根线都要上拉（开漏输出， idle 为高）。

**时序**：
- **START**：SCL 高时 SDA 由高拉低。
- **STOP**：SCL 高时 SDA 由低拉高。
- 数据：SCL 低时改 SDA，SCL 高时采样。
- **ACK**：每 8 位后接收方拉低 SDA 一个周期回 ACK，发送方释放 SDA 读回。

**寻址**：主设备发 `START + 7位地址 + R/W`，匹配地址的从设备回 ACK，其他从设备不理。多个主同时发起靠总线仲裁（线与，先拉低的赢，输的退出发重试）。

**速率档**：Standard 100k、Fast 400k、Fast+ 1M、High-Speed 3.4M。绝大多数传感器用 100k–400k。高速对上拉电阻和线电容敏感——400k 以上要算 RC 时间常数，上拉电阻选 2.2k–4.7k。

**优点**：引脚极省、可挂多设备、协议规范统一。
**缺点**：
- 慢，不适合大块数据传输。
- 单点故障敏感：一个设备把 SDA 拉死，整条总线锁死（总线恢复机制：发 9 个时钟脉冲解锁）。
- 地址冲突：两个同地址设备挂不上，需改地址或用多路开关。

**典型用途**：MPU6050（IMU）、BME280（温湿压）、OLED 屏（SSD1306）、EEPROM（24Cxx）、RTC（DS3231）。

**常见坑**：
1. 忘上拉电阻 → 总线永远拉不起来，全 0xFF。
2. 地址错：传感器常用 0x68/0x76/0x3C 等，文档写"7 位地址"还是"含 R/W 的 8 位"经常混淆， datasheet 多读几遍。
3. SCL/SDA 接反 → 同样全 0xFF，万用表/分析仪最有效。
4. 总线挂死：某从设备在中间崩了卡住 SDA，主设备重发 START 也无效。对策：人为发 9 个 SCL 时钟 + STOP 复位总线（Linux I2C 核心驱动自带恢复）。

## 四、SPI：高速主从总线

**接线**：四线
- **SCLK**：主设备输出时钟。
- **MOSI**：主出从入（Master Out Slave In）。
- **MISO**：主入从出（Master In Slave Out）。
- **CS/SS**：片选，每挂一个从设备拉一根 CS 线，选中谁谁才响应。

**时序**：主设备拉低某从设备 CS → 产生 SCLK → 每个 clock 边沿主从各移一位（MOSI 出、MISO 入），全双工。时钟极性（CPOL）和相位（CPHA）组合 4 种模式（Mode 0–3），主从必须一致。

**速率**：几十 Mbps 起步，快的能上 100 Mbps+。STM32 SPI 能跑 50M+，ESP32 80M+。比 I2C 快一个量级。

**优点**：快、全双工、时序简单（硬件实现成本低）、无地址冲突（靠 CS 区分）。
**缺点**：
- 引脚多：每个从设备一根 CS，挂 5 个外设就 5 根 CS。
- 无固定寻址/应答：主设备发出去，收没收到无法硬件确认（靠协议本身校验）。
- 距离短：高频信号线长就出错，板内为主。

**典型用途**：W25Q Flash、SD 卡（SPI 模式）、TFT/OLE（SSD1331/ILI9341）、ADC（ADS1256）、以太网芯片（W5500）。

**DMA 配合**：SPI 传大块数据（屏刷帧）几乎一定配 DMA，否则 CPU 全卡在移位循环里。

**常见坑**：
1. CPOL/CPHA 配错：数据能收到但是错位/移位，对照 datasheet 时序图调 Mode 0–3。
2. 时钟太快：超出从设备上限（如某 Flash 上限 33M，主设 50M 乱码），降速。
3. CS 抖动：传输中 CS 抬起再拉低，从设备把半截当新事务，丢字节。
4. MISO 没接或从设备不驱动：读回全 0xFF。

## 五、CAN：差分总线，可靠仲裁

**接线**：CAN_H、CAN_L 两根差分线，总线两端各加 120Ω 终端电阻。所有节点并联挂总线。

**差分信号**：显性（0）时 CAN_H-CAN_L ≈ 2V，隐性（1）时 ≈ 0V。差分抗干扰强，几十米到几百米无中继。

**仲裁**：多节点同时发，靠 ID 逐位仲裁——ID 越小优先级越高，赢的继续发、输的退避。无损仲裁，不像以太网 CSMA/CD 会丢帧。

**帧结构**：SOF + ID（11 位标准帧/29 位扩展帧）+ RTR + 控制 + 数据（0–8 字节，CAN-FD 可到 64）+ CRC + ACK + EOF。

**优点**：抗干扰、远距离、仲裁无损、错误检测强（CRC + 位填充 + 错误帧），工业/汽车首选。
**缺点**：8 字节数据小（要分包）、速率不高（1Mbps 在 40m 内，越长越降）。

**典型用途**：汽车 ECU 互联、OBD-II 诊断口、电机驱动/PLC、农机、AGV。

**常见坑**：
1. 终端电阻缺失：总线两端不加 120Ω，信号反射乱码。
2. 节点波特率不一致：和 UART 一样，全乱码。
3. 单节点无法自测：CAN 至少要两个节点（一个发一个回 ACK），单节点收不到 ACK 会一直重发。调试时用 CAN 分析仪做对端。
4. 帧丢失：高优先级 ID 长期占用总线，低优先级饿死。

